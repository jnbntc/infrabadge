#!/usr/bin/env python3
"""Compile the original, repo-owned M1 5x7 font; standard library only."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def generate():
    font = json.loads((ROOT / 'assets/ui-font5x7.json').read_text())
    lines = ['/* Generated by tools/generate_ui_font.py; original InfraBadge glyphs. */',
             'typedef struct { char code; unsigned char rows[7]; } ui_glyph_t;',
             'static const ui_glyph_t ui_glyphs[] = {']
    for char, rows in sorted(font.items()):
        assert len(char) == 1 and 32 <= ord(char) < 127 and char not in "'\\"
        assert len(rows) == 7 and all(len(row) == 5 and set(row) <= {'0', '1'} for row in rows)
        lines.append("    {'%s', {%s}}," % (char, ', '.join('0x%02x' % int(row, 2) for row in rows)))
    return '\n'.join(lines + ['};', ''])
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'components/ui/generated/ui_font.h'
    content = generate()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Stale M1 font: run python3 tools/generate_ui_font.py')
    else:
        target.write_text(content)
if __name__ == '__main__':
    main()
