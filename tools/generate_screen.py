#!/usr/bin/env python3
"""Generate a small font/layout header and expected image. No external packages."""
import argparse
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
WIDTH = HEIGHT = 200

def load_assets():
    glyphs = json.loads((ROOT / 'assets/font5x7.json').read_text())
    lines = json.loads((ROOT / 'assets/m0-screen.json').read_text())
    for rows in glyphs.values():
        if len(rows) != 7 or any(len(row) != 5 or set(row) - {'0', '1'} for row in rows):
            raise ValueError('Malformed glyph')
    for line in lines:
        if any(c not in glyphs for c in line['text']):
            raise ValueError('Unsupported glyph')
        x, y, scale = line['x'], line['y'], line['scale']
        if x < 0 or y < 0 or not 1 <= scale <= 28 or not line['text'] or x + (len(line['text']) * 6 - 1) * scale > WIDTH or y + 7 * scale > HEIGHT:
            raise ValueError('Text outside screen')
    return glyphs, lines

def render(glyphs, lines):
    frame = bytearray([255]) * 5000
    def pixel(x, y):
        frame[y * 25 + x // 8] &= ~(0x80 >> (x % 8))
    for x in range(4, 196):
        pixel(x, 4); pixel(x, 195)
    for y in range(4, 196):
        pixel(4, y); pixel(195, y)
    for line in lines:
        x, y, scale = line['x'], line['y'], line['scale']
        for char in line['text']:
            for row, bits in enumerate(glyphs[char]):
                for col, bit in enumerate(bits):
                    if bit == '1':
                        for dy in range(scale):
                            for dx in range(scale):
                                pixel(x + col * scale + dx, y + row * scale + dy)
            x += 6 * scale
    return bytes(frame)

def png(frame, level=-1):
    def chunk(kind, data):
        return struct.pack('!I', len(data)) + kind + data + struct.pack('!I', zlib.crc32(kind + data))
    rows = b''.join(b'\0' + frame[y * 25:(y + 1) * 25] for y in range(200))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('!2I5B', 200, 200, 1, 0, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(rows, level)) + chunk(b'IEND', b'')

def png_pixels(data):
    """Compare decoded pixels, not implementation-specific deflate streams."""
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('Invalid PNG signature')
    offset, header, compressed = 8, None, b''
    ended = False
    while offset < len(data):
        length = struct.unpack_from('!I', data, offset)[0]
        kind = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        crc = struct.unpack_from('!I', data, offset + 8 + length)[0]
        if zlib.crc32(kind + payload) != crc:
            raise ValueError('Invalid PNG CRC')
        if kind == b'IHDR':
            header = payload
        elif kind == b'IDAT':
            compressed += payload
        elif kind == b'IEND':
            ended = True
        else:
            raise ValueError('Unexpected PNG chunk')
        offset += length + 12
    if not ended or header != struct.pack('!2I5B', 200, 200, 1, 0, 0, 0, 0):
        raise ValueError('Unexpected PNG format')
    rows = zlib.decompress(compressed)
    if len(rows) != 5200 or any(rows[y * 26] != 0 for y in range(200)):
        raise ValueError('Unexpected PNG scanlines')
    return b''.join(rows[y * 26 + 1:(y + 1) * 26] for y in range(200))

def outputs():
    glyphs, lines = load_assets()
    header = '/* Generated by tools/generate_screen.py. Original glyphs. */\n#pragma once\n'
    header += 'static const struct { char code; uint8_t rows[7]; } glyphs[] = {\n'
    for char, rows in sorted(glyphs.items()):
        header += "    {'" + char + "', {" + ', '.join(str(int(row, 2)) for row in rows) + '}},\n'
    header += '};\nstatic const struct { const char *text; int x, y; unsigned scale; } lines[] = {\n'
    for line in lines:
        header += '    {' + json.dumps(line['text']) + f", {line['x']}, {line['y']}, {line['scale']}" + '},\n'
    header += '};\n'
    frame = render(glyphs, lines)
    # PBM uses black=1; panel framebuffer uses white=1.
    pbm = b'P4\n200 200\n' + bytes(x ^ 255 for x in frame)
    return {'components/render/generated/screen_data.h': header.encode(), 'docs/m0-screen.png': png(frame), 'tests/fixtures/m0.pbm': pbm}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, data in outputs().items():
        path = ROOT / name
        if args.check:
            actual = path.read_bytes() if path.is_file() else b''
            matches = png_pixels(actual) == png_pixels(data) if name.endswith('.png') and actual else actual == data
            if not matches:
                raise SystemExit(f'Stale generated asset: {name}')
        else:
            path.write_bytes(data)
    print('Generated assets match' if args.check else 'Generated M0 font/layout and expected screen')

if __name__ == '__main__':
    main()
